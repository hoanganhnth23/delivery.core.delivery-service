CREATE TABLE IF NOT EXISTS deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    shipper_id BIGINT NULL,
    status VARCHAR(32) NULL,
    pickup_address TEXT NULL,
    pickup_lat DOUBLE PRECISION NULL,
    pickup_lng DOUBLE PRECISION NULL,
    delivery_address TEXT NULL,
    delivery_lat DOUBLE PRECISION NULL,
    delivery_lng DOUBLE PRECISION NULL,
    shipper_current_lat DOUBLE PRECISION NULL,
    shipper_current_lng DOUBLE PRECISION NULL,
    assigned_at TIMESTAMP NULL,
    picked_up_at TIMESTAMP NULL,
    delivered_at TIMESTAMP NULL,
    estimated_delivery_time TIMESTAMP NULL,
    total_price DECIMAL(12,2) NULL,
    payment_method VARCHAR(64) NULL,
    notes TEXT NULL,
    reject_reason TEXT NULL,
    created_at TIMESTAMP NULL,
    updated_at TIMESTAMP NULL,
    creator_id BIGINT NOT NULL,
    restaurant_id BIGINT NULL,
    CONSTRAINT uk_deliveries_order_id UNIQUE (order_id)
);
